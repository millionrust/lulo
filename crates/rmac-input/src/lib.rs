//! Persistent keyboard, mouse, and touchpad settings for a niri session.
//!
//! The service traverses niri's positional include graph and owns only one
//! final managed include. A same-directory candidate is validated by niri
//! before either live file changes; niri then applies the change through config
//! hot reload.

use kdl::{KdlDocument, KdlNode, KdlValue};
use std::collections::HashSet;
use std::fmt;
use std::io::Read as _;
#[cfg(unix)]
use std::io::{BufRead as _, Write as _};
use std::path::{Path, PathBuf};
use std::process::{Command, ExitStatus, Stdio};
use std::sync::atomic::{AtomicU64, Ordering};

static CANDIDATE_SEQUENCE: AtomicU64 = AtomicU64::new(0);
const MANAGED_CONFIG_NAME: &str = ".rmac-input.kdl";
const MANAGED_HEADER: &str = "// Managed by rmac System Settings. Do not edit this file by hand.";
const MAX_INCLUDE_DEPTH: usize = 10;
const MAX_CONFIG_FILES: usize = 64;
const MAX_CONFIG_BYTES: u64 = 2 * 1024 * 1024;
const MAX_GRAPH_BYTES: u64 = 8 * 1024 * 1024;
const MAX_COMMAND_OUTPUT_BYTES: usize = 4 * 1024 * 1024;
const COMMAND_TIMEOUT: std::time::Duration = std::time::Duration::from_secs(10);
#[cfg(unix)]
const RELOAD_TIMEOUT: std::time::Duration = std::time::Duration::from_secs(3);

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum AccelProfile {
    #[default]
    Adaptive,
    Flat,
}

impl AccelProfile {
    pub fn label(self) -> &'static str {
        match self {
            Self::Adaptive => "Adaptive",
            Self::Flat => "Flat",
        }
    }

    fn id(self) -> &'static str {
        match self {
            Self::Adaptive => "adaptive",
            Self::Flat => "flat",
        }
    }
}

#[derive(Clone, Debug, PartialEq)]
pub struct KeyboardSettings {
    pub repeat_delay_ms: u32,
    pub repeat_rate: u32,
    pub numlock: bool,
    pub xkb_override: Option<XkbOverride>,
}

impl Default for KeyboardSettings {
    fn default() -> Self {
        Self {
            repeat_delay_ms: 600,
            repeat_rate: 25,
            numlock: false,
            xkb_override: None,
        }
    }
}

