def squircle_path(half: float = PLATE / 2, n: float = N, steps: int = 96) -> str:
    """|x/a|^n + |y/a|^n = 1 about the canvas centre, as a closed path."""
    c = SIZE / 2
    pts = []
    for i in range(steps):
        t = 2.0 * math.pi * i / steps
        ct, st = math.cos(t), math.sin(t)
        x = math.copysign(abs(ct) ** (2.0 / n), ct) * half
        y = math.copysign(abs(st) ** (2.0 / n), st) * half
        pts.append(f"{c + x:.1f} {c + y:.1f}")
    return "M" + "L".join(pts) + "Z"


def mix(a: str, b: str, t: float) -> str:
    """Blend two #RRGGBB colours; t = 0 gives a, 1 gives b."""
    pa = [int(a[i:i + 2], 16) for i in (1, 3, 5)]
    pb = [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return "#%02X%02X%02X" % tuple(round(x + (y - x) * t) for x, y in zip(pa, pb))


def grad(gid: str, top: str, bottom: str, top_op: float = 1, bottom_op: float = 1,
         x2: float = 0, y2: float = 1) -> str:
    return (f'<linearGradient id="{gid}" x1="0" y1="0" x2="{x2}" y2="{y2}">'
            f'<stop offset="0" stop-color="{top}" stop-opacity="{top_op}"/>'
            f'<stop offset="1" stop-color="{bottom}" stop-opacity="{bottom_op}"/>'
            f'</linearGradient>')


