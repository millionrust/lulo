#[test]
fn dispatcher_endpoints_are_action_scoped() {
    let runtime = Path::new("/tmp/rmac-shortcuts-test");
    let launcher = shortcut_socket_path_in(runtime, &ShortcutId("launcher".into())).unwrap();
    let drawer = shortcut_socket_path_in(runtime, &ShortcutId("app-drawer".into())).unwrap();
    assert_ne!(launcher, drawer);
    assert!(launcher.ends_with("shortcut-launcher.sock"));
    assert!(drawer.ends_with("shortcut-app-drawer.sock"));
    assert!(shortcut_socket_path_in(runtime, &ShortcutId("unknown".into())).is_err());
}

#[test]
fn the_power_button_and_its_dialog_have_their_own_endpoints() {
    let runtime = Path::new("/tmp/rmac-shortcuts-test");
    let press = ShortcutId(power_key::POWER_KEY_SHORTCUT.into());
    let dialog = ShortcutId(power_key::SHUTDOWN_DIALOG_SHORTCUT.into());
    assert!(shortcut_socket_path_in(runtime, &press)
        .unwrap()
        .ends_with("shortcut-power-key.sock"));
    assert!(shortcut_socket_path_in(runtime, &dialog)
        .unwrap()
        .ends_with("shortcut-shutdown-dialog.sock"));
    // Neither is a user shortcut: niri binds the key itself in shell.kdl,
    // so neither is offered to the GlobalShortcuts portal or the fallback.
    assert!(!default_shortcuts()
        .iter()
        .any(|spec| spec.id == press || spec.id == dialog));
}

#[test]
fn ctrl_f2_moves_menu_bar_focus_through_its_own_endpoint() {
    let runtime = Path::new("/tmp/rmac-shortcuts-test");
    let focus = ShortcutId("menu-bar-focus".into());
    assert!(known_action(&focus));
    assert!(shortcut_socket_path_in(runtime, &focus)
        .unwrap()
        .ends_with("shortcut-menu-bar-focus.sock"));
    // Not a user shortcut: niri binds Ctrl+F2 itself in shell.kdl, the same
    // way it binds the power key, so this isn't offered to the
    // GlobalShortcuts portal or the fallback either.
    assert!(!default_shortcuts().iter().any(|spec| spec.id == focus));
}

