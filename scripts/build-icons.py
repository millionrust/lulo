#!/usr/bin/env python3
"""Generate every rmac first-party icon from one glass recipe.

The recipe was measured from the owner's Mac Dock (macOS 26.2, Retina capture,
64 pt tiles): the visible icon is a 104 px (52 pt) squircle in a 128 px tile —
824 of a 1024 canvas — and its corner profile fits a superellipse with
n = 4.2 (inset 25, 11, 6, 1, 0 px at rows 0, 5, 10, 20, 27). Nothing is copied
from Apple's artwork; only the lighting was measured:

  body   vertical gradient, top ≈ 1.3× brighter than the bottom
  sheen  a soft white glow from the top-left
  rim    ≈ 1 px (8 of 1024) inner edge, brightest at the top-left corner
         (+65 over the body), again at the bottom-right (+50), weakest on the
         other two corners (+25)
  glyph  frosted white: opaque at the top, ≈ 80 % at the bottom, a bright
         top edge and a small soft shadow below it
  plate  no drop shadow of its own (the Dock shelf shows none)
  trash  no plate: a glass bin 94 × 102 px of the 128 px tile, 3 px below
         the plate top, 70 px wide at the base

Every plated icon is emitted in four appearances (default, dark, clear,
tinted). Outputs, all regenerated by one run:

  assets/icons/<name>[-<appearance>].svg      1024 masters for the design lab
  packaging/rmac-apps/icons/org.rmac.<App>.svg installed app icons
  crates/rmac-dock/assets/icons/<name>.svg     the Dock's embedded artwork

Installed and Dock copies declare a 128 px intrinsic size: GPUI rasterises an
SVG image at twice its intrinsic size, so 256 px covers a 64 pt tile at 2×
with room for magnification.

Usage:
    python3 scripts/build-icons.py            # rewrite every output
    python3 scripts/build-icons.py --check    # fail if any output is stale
"""

