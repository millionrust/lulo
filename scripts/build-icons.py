def build(name: str, appearance: str = "default", px: int = SIZE) -> str:
    plate_colours, icon_defs, glyph = ICONS[name]
    shadow = "#000000"
    parts = []
    defs = [icon_defs]

    if plate_colours is not None:
        top, bottom = plate_colours
        if appearance == "dark":
            top, bottom = mix(top, "#000000", .45), mix(bottom, "#000000", .55)
        elif appearance == "clear":
            top, bottom = "#FFFFFF", "#DCDCE2"
        shadow = mix(bottom, "#000000", .5)
        plate = squircle_path()
        defs += [
            f'<clipPath id="sq"><path d="{plate}"/></clipPath>',
            grad("body", top, bottom, *((.30, .22) if appearance == "clear" else (1, 1))),
            '<radialGradient id="sheen" cx=".22" cy=".06" r=".9">'
            '<stop offset="0" stop-color="#FFFFFF" stop-opacity=".22"/>'
            '<stop offset=".6" stop-color="#FFFFFF" stop-opacity="0"/></radialGradient>',
            '<linearGradient id="rim" x1="0" y1="0" x2="1" y2="1">'
            '<stop offset="0" stop-color="#FFFFFF" stop-opacity=".78"/>'
            '<stop offset=".32" stop-color="#FFFFFF" stop-opacity=".28"/>'
            '<stop offset=".62" stop-color="#FFFFFF" stop-opacity=".2"/>'
            '<stop offset="1" stop-color="#FFFFFF" stop-opacity=".6"/></linearGradient>',
        ]
        parts.append(f"""<g clip-path="url(#sq)">
  <rect x="0" y="0" width="{SIZE}" height="{SIZE}" fill="url(#body)"/>
  <rect x="0" y="0" width="{SIZE}" height="{SIZE}" fill="url(#sheen)"/>
  <path d="{plate}" fill="none" stroke="url(#rim)" stroke-width="{2 * RIM}"/>
</g>""")

    defs += [
        grad("frost", "#FFFFFF", mix("#FFFFFF", plate_colours[0] if plate_colours else
                                     "#FFFFFF", .12), 1, .82),
        grad("edge", "#FFFFFF", "#FFFFFF", .95, .3),
        '<filter id="lift" x="-20%" y="-20%" width="140%" height="150%">'
        f'<feDropShadow dx="0" dy="10" stdDeviation="12" flood-color="{shadow}" '
        'flood-opacity=".3"/></filter>',
    ]
    if appearance == "tinted":
        defs.append('<filter id="mono"><feColorMatrix type="saturate" values="0"/></filter>')
    if appearance == "dark" and plate_colours is None:
        defs.append('<filter id="dim"><feColorMatrix type="matrix" values=".78 0 0 0 0 '
                    '0 .78 0 0 0 0 0 .8 0 0 0 0 0 1 0"/></filter>')

    wrap = {"clear": '<g opacity=".9">'}.get(
        appearance, '<g filter="url(#dim)">' if appearance == "dark"
        and plate_colours is None else "<g>")
    if plate_colours is not None:
        # Glyphs are drawn on a 1024 grid and enlarged about the centre so
        # they fill the plate as the Mac's do (≈ 70 % of its width).
        glyph = f'<g transform="translate(512 512) scale({GLYPH_SCALE}) translate(-512 -512)">{glyph}</g>'
    parts.append(f"{wrap}{glyph}\n</g>")

    body = "\n".join(parts)
    if appearance == "tinted":
        # Monochrome: the whole icon, plate included, loses its colour.
        body = f'<g filter="url(#mono)">\n{body}\n</g>'
    size_attr = f' width="{px}" height="{px}"'
    return (f'<?xml version="1.0" encoding="UTF-8"?>\n{LICENSE}\n'
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE} {SIZE}"{size_attr}>\n'
            f'<defs>{"".join(defs)}</defs>\n{body}\n</svg>\n')


def outputs() -> dict[Path, str]:
    files: dict[Path, str] = {}
    for name in ICONS:
        for appearance in APPEARANCES:
            suffix = "" if appearance == "default" else f"-{appearance}"
            files[ROOT / "assets/icons" / f"{name}{suffix}.svg"] = build(name, appearance)
    for identity, name in PACKAGED.items():
        files[ROOT / "packaging/rmac-apps/icons" / f"{identity}.svg"] = build(name, px=128)
    for file, name in DOCK.items():
        files[ROOT / "crates/rmac-dock/assets/icons" / f"{file}.svg"] = build(name, px=128)
    return files


def main(argv: list[str]) -> int:
    files = outputs()
    if "--check" in argv:
        stale = [p for p, text in files.items()
                 if not p.is_file() or p.read_text() != text]
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}")
        return 1 if stale else 0
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"wrote {len(files)} icons; preview them in design-lab/icons.html")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
