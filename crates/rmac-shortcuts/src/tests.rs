#[test]
fn generated_niri_mode_never_combines_portal_and_fallback_bindings() {
    let root = std::env::temp_dir().join(format!(
        "rmac-shortcut-mode-{}-{}",
        std::process::id(),
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .subsec_nanos()
    ));
    let path = root.join("rmac/niri/shortcuts-generated.kdl");
    let dispatcher = Path::new("/usr/libexec/rmac/rmac-shortcut-dispatch");
    write_niri_binding_mode(
        &path,
        dispatcher,
        &BackendStatus::FallbackRequired {
            reason: "test".into(),
        },
    )
    .unwrap();
    let fallback = std::fs::read_to_string(&path).unwrap();
    assert!(fallback.contains("Mod+Space"));
    assert_eq!(fallback.matches("{ spawn ").count(), 2);

    write_niri_binding_mode(
        &path,
        dispatcher,
        &BackendStatus::Portal {
            version: 2,
            can_configure: true,
        },
    )
    .unwrap();
    let portal = std::fs::read_to_string(&path).unwrap();
    assert!(portal.contains("GlobalShortcuts portal owns"));
    assert!(!portal.contains("binds"));
    std::fs::remove_dir_all(root).unwrap();
}

